import { colorNames, dark, light, radius, type Palette } from '../src/tokens.ts';

const vars = (p: Palette, indent = '  ') =>
  colorNames.map((n) => `${indent}--color-${n}: ${p[n]};`).join('\n');

const radiusVars = Object.entries(radius)
  .map(([k, v]) => `  --radius-${k}: ${v};`)
  .join('\n');

const header = '/* Generated by @tadriss/ui-tokens — do not edit. */\n';

/** Tailwind v4 (web). Dark mode is class-based (next-themes adds `.dark` to <html>). */
export function webCss(): string {
  const theme = colorNames.map((n) => `  --color-${n}: rgb(var(--color-${n}));`).join('\n');
  return `${header}
:root {
${vars(light)}
${radiusVars}
}

.dark {
${vars(dark)}
}

@theme inline {
${theme}
${Object.keys(radius)
  .map((k) => `  --radius-${k}: var(--radius-${k});`)
  .join('\n')}
}
`;
}

/** NativeWind v4 (mobile). `.dark:root` is toggled by NativeWind's colorScheme. */
export function mobileCss(): string {
  return `${header}
@tailwind base;
@tailwind components;
@tailwind utilities;

:root {
${vars(light)}
}

.dark:root {
${vars(dark)}
}
`;
}

/** Tailwind v3 preset consumed by apps/mobile/tailwind.config.js. */
export function nativewindPreset(): string {
  const colors = Object.fromEntries(
    colorNames.map((n) => [n, `rgb(var(--color-${n}) / <alpha-value>)`]),
  );
  return `${header}module.exports = ${JSON.stringify(
    { darkMode: 'class', theme: { extend: { colors, borderRadius: radius } } },
    null,
    2,
  )};\n`;
}
