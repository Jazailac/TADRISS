import {
  colorNames,
  dark,
  directionThemes,
  light,
  radius,
  motion,
  typeScale,
  spacing,
  type Palette,
} from '../src/tokens.ts';

const vars = (p: Palette, indent = '  ') =>
  colorNames.map((n) => `${indent}--color-${n}: ${p[n]};`).join('\n');

const radiusVars = Object.entries(radius)
  .map(([k, v]) => `  --radius-${k}: ${v};`)
  .join('\n');

const header = '/* Generated by @tadriss/ui-tokens — do not edit. */\n';

const directionVars = Object.entries(directionThemes)
  .map(([key, theme]) => {
    const vars = Object.entries(theme)
      .map(([name, value]) => `  --direction-${name}: ${value};`)
      .join('\n');
    return `.direction-${key} {\n${vars}\n}`;
  })
  .join('\n\n');

/** Layered, warm-tinted shadows. Dark mode uses stronger alpha (black on near-black). */
const shadow = (k: number) => ({
  xs: `0 1px 2px rgb(var(--color-shadow) / ${0.06 * k})`,
  sm: `0 1px 2px rgb(var(--color-shadow) / ${0.05 * k}), 0 2px 8px -2px rgb(var(--color-shadow) / ${0.06 * k})`,
  md: `0 1px 2px rgb(var(--color-shadow) / ${0.04 * k}), 0 8px 24px -6px rgb(var(--color-shadow) / ${0.1 * k})`,
  lg: `0 2px 4px rgb(var(--color-shadow) / ${0.04 * k}), 0 24px 56px -16px rgb(var(--color-shadow) / ${0.2 * k})`,
});
const shadowVars = (k: number) =>
  Object.entries(shadow(k))
    .map(([n, v]) => `  --tadriss-shadow-${n}: ${v};`)
    .join('\n');

/** Tailwind v4 (web). Dark mode is class-based (next-themes adds `.dark` to <html>). */
export function webCss(): string {
  const theme = colorNames.map((n) => `  --color-${n}: rgb(var(--color-${n}));`).join('\n');
  return `${header}
:root {
${vars(light)}
${radiusVars}
${Object.entries(motion)
  .map(([k, v]) => `  --motion-${k}: ${v};`)
  .join('\n')}
${Object.entries(typeScale)
  .map(([k, v]) => `  --type-${k}: ${v};`)
  .join('\n')}
${Object.entries(spacing)
  .map(([k, v]) => `  --space-${k}: ${v};`)
  .join('\n')}
${shadowVars(1)}
}

.dark {
${vars(dark)}
${shadowVars(4)}
}

@theme inline {
${theme}
${Object.keys(radius)
  .map((k) => `  --radius-${k}: var(--radius-${k});`)
  .join('\n')}
${Object.keys(shadow(1))
  .map((k) => `  --shadow-${k}: var(--tadriss-shadow-${k});`)
  .join('\n')}
}

${directionVars}
`;
}

/** NativeWind v4 (mobile). `.dark:root` is toggled by NativeWind's colorScheme. */
export function mobileCss(): string {
  return `${header}
@tailwind base;
@tailwind components;
@tailwind utilities;

:root {
${vars(light)}
}

.dark:root {
${vars(dark)}
}
`;
}

/** Tailwind v3 preset consumed by apps/mobile/tailwind.config.js. */
export function nativewindPreset(): string {
  const colors = Object.fromEntries(
    colorNames.map((n) => [n, `rgb(var(--color-${n}) / <alpha-value>)`]),
  );
  return `${header}module.exports = ${JSON.stringify(
    { darkMode: 'class', theme: { extend: { colors, borderRadius: radius } } },
    null,
    2,
  )};\n`;
}
